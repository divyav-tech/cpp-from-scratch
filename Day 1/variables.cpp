#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 20;
    int sum = a + b;
    bool isTrue = true;

    cout << "The value of a is " << a;
    cout << "\nThe value of b is " << b;
    cout << "\nThe sum of a and b is " << sum << "\n";
    cout << a << " + " << b << " is " << sum << "\n";
    cout << isTrue;              // true = 1, false = 0

    return 0;
}